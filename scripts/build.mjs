// Builds the static site for one brand into dist/.
//
//   BRAND=bb node scripts/build.mjs     (defaults to rwc)
//
// Copies the shared app files, fills the {{placeholders}} in index.html from
// brands/<id>/brand.json, and writes dist/brand/ (brand.js, brand.css, logos).
// The Netlify functions read the same brand.json via process.env.BRAND.

import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const brandId = process.env.BRAND || 'rwc';
const brandDir = join(root, 'brands', brandId);
if (!existsSync(join(brandDir, 'brand.json'))) {
  console.error(`Unknown BRAND "${brandId}" — expected brands/${brandId}/brand.json`);
  process.exit(1);
}
const brand = JSON.parse(readFileSync(join(brandDir, 'brand.json'), 'utf8'));

const out = join(root, 'dist');
rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'brand'), { recursive: true });

const SHARED = ['style.css', 'app.js', 'generate.js', 'pdf.js', 'email.js', 'macros.js', 'data', 'assets'];
for (const path of SHARED) cpSync(join(root, path), join(out, path), { recursive: true });

cpSync(join(brandDir, 'assets'), join(out, 'brand'), { recursive: true });
cpSync(join(brandDir, 'brand.css'), join(out, 'brand', 'brand.css'));
writeFileSync(join(out, 'brand', 'brand.js'),
  `// Generated by scripts/build.mjs from brands/${brandId}/brand.json\nwindow.BRAND = ${JSON.stringify(brand, null, 2)};\n`);

const escapeHtml = value => String(value)
  .replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const lookup = key => key.split('.').reduce((obj, part) => obj?.[part], brand);
const html = readFileSync(join(root, 'index.html'), 'utf8').replace(/\{\{([\w.]+)\}\}/g, (_, key) => {
  const value = lookup(key);
  if (value === undefined) throw new Error(`index.html uses {{${key}}}, which brands/${brandId}/brand.json doesn't define`);
  return escapeHtml(value);
});
writeFileSync(join(out, 'index.html'), html);

console.log(`Built ${brand.appName} (${brandId}) → dist/`);
